import { Matrix3, Vector3 } from "three";

/**
 * The icosahedral rotation group I (order 60) — the symmetry every
 * Kaleidoscope design takes. It is the richest polyhedral group, and the
 * one the soccer ball has.
 *
 * Rotation-only on purpose. Swirling seams are handed, and seeds that
 * wander would collide with their own mirror images on mirror planes; the
 * rotation group only fixes points on its axes.
 *
 * The group also carries its three special orbits — the points a rotation
 * axis passes through: 12 five-fold, 20 three-fold, 30 two-fold. A seed on
 * an axis has a smaller orbit (it is its own image under that axis'
 * rotations); these are the soccer ball's pentagon and hexagon centers.
 */
export interface RotationGroup {
  elements: Matrix3[];
  /** Special orbits, smallest first (12, 20, 30). */
  specialOrbits: Vector3[][];
  /**
   * The tetrahedral subgroup T (order 12), used for coloring: panels are
   * colored by their orbit under it, so one family of 60 swirls splits
   * into 5 sets of 12 (the five-tetrahedra compound). Colors then have
   * tetrahedral symmetry while the seams keep the full icosahedral one.
   */
  colorSubgroup: Matrix3[];
}

const PHI = (1 + Math.sqrt(5)) / 2;

const VERTICES: [number, number, number][] = [
  [-1, PHI, 0],
  [1, PHI, 0],
  [-1, -PHI, 0],
  [1, -PHI, 0],
  [0, -1, PHI],
  [0, 1, PHI],
  [0, -1, -PHI],
  [0, 1, -PHI],
  [PHI, 0, -1],
  [PHI, 0, 1],
  [-PHI, 0, -1],
  [-PHI, 0, 1],
];

const FACES: [number, number, number][] = [
  [0, 11, 5],
  [0, 5, 1],
  [0, 1, 7],
  [0, 7, 10],
  [0, 10, 11],
  [1, 5, 9],
  [5, 11, 4],
  [11, 10, 2],
  [10, 7, 6],
  [7, 1, 8],
  [3, 9, 4],
  [3, 4, 2],
  [3, 2, 6],
  [3, 6, 8],
  [3, 8, 9],
  [4, 9, 5],
  [2, 4, 11],
  [6, 2, 10],
  [8, 6, 7],
  [9, 8, 1],
];

let cached: RotationGroup | null = null;

export function icosahedralGroup(): RotationGroup {
  return (cached ??= buildGroup());
}

/**
 * Every rotation mapping the icosahedron onto itself: send one vertex and
 * an adjacent vertex onto each (vertex, neighbour) pair. Frames are built
 * from the pair's directions, so each rotation is exact.
 */
function buildGroup(): RotationGroup {
  const verts = VERTICES.map(([x, y, z]) => new Vector3(x, y, z).normalize());
  const neighbors = verts.map(() => new Set<number>());
  for (const f of FACES) {
    for (let k = 0; k < 3; k++) {
      neighbors[f[k]].add(f[(k + 1) % 3]);
      neighbors[f[(k + 1) % 3]].add(f[k]);
    }
  }
  const frame = (a: Vector3, b: Vector3) => {
    const u = b.clone().projectOnPlane(a).normalize();
    return new Matrix3().set(
      a.x, u.x, a.y * u.z - a.z * u.y,
      a.y, u.y, a.z * u.x - a.x * u.z,
      a.z, u.z, a.x * u.y - a.y * u.x,
    );
  };
  const b0 = [...neighbors[0]][0];
  const inv = frame(verts[0], verts[b0]).transpose();
  const elements: Matrix3[] = [];
  for (let i = 0; i < verts.length; i++) {
    for (const j of neighbors[i]) elements.push(frame(verts[i], verts[j]).multiply(inv));
  }
  // Identity first, so element 0 of every orbit is its representative.
  const idIdx = elements.findIndex((m) => sameMatrix(m, new Matrix3()));
  [elements[0], elements[idIdx]] = [elements[idIdx], elements[0]];

  const [f0, f1, f2] = FACES[0];
  const faceCenter = verts[f0].clone().add(verts[f1]).add(verts[f2]).normalize();
  const edgeMid = verts[f0].clone().add(verts[f1]).normalize();
  const specialOrbits = [verts[0], faceCenter, edgeMid].map((p) => orbitOf(p, elements));
  return { elements, specialOrbits, colorSubgroup: findSubgroup(elements, 12) };
}

/** Distinct images of `p` under the group, in group-element order. */
export function orbitOf(p: Vector3, elements: Matrix3[]): Vector3[] {
  const out: Vector3[] = [];
  for (const m of elements) {
    const q = p.clone().applyMatrix3(m);
    if (!out.some((o) => o.distanceToSquared(q) < 1e-12)) out.push(q);
  }
  return out;
}

/**
 * First subgroup of the given order generated by a pair of elements, in
 * deterministic element order.
 */
function findSubgroup(elements: Matrix3[], order: number): Matrix3[] {
  for (let i = 1; i < elements.length; i++) {
    for (let j = i; j < elements.length; j++) {
      const closure = [elements[0]];
      const queue = [elements[i], elements[j]];
      while (queue.length && closure.length <= order) {
        const m = queue.pop()!;
        if (closure.some((c) => sameMatrix(c, m))) continue;
        closure.push(m);
        for (const c of [...closure]) queue.push(m.clone().multiply(c), c.clone().multiply(m));
      }
      if (closure.length === order) return closure;
    }
  }
  return [elements[0]];
}

function sameMatrix(a: Matrix3, b: Matrix3): boolean {
  for (let k = 0; k < 9; k++) if (Math.abs(a.elements[k] - b.elements[k]) > 1e-6) return false;
  return true;
}
